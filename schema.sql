-- 1. Crear tabla registros
CREATE TABLE IF NOT EXISTS public.registros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    parcela TEXT NOT NULL,
    cultivo TEXT NOT NULL,
    actividad TEXT NOT NULL,
    observaciones TEXT,
    creado TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.registros ENABLE ROW LEVEL SECURITY;

-- 3. Políticas de acceso (lectura e inserción para la aplicación web)
CREATE POLICY "Permitir lectura pública de registros"
ON public.registros
FOR SELECT
USING (true);

CREATE POLICY "Permitir inserción pública de registros"
ON public.registros
FOR INSERT
WITH CHECK (true);
