-- 1. Crear tabla registros (si no existe)
CREATE TABLE IF NOT EXISTS public.registros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    parcela TEXT NOT NULL,
    cultivo TEXT NOT NULL,
    actividad TEXT NOT NULL,
    observaciones TEXT,
    creado TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.registros ENABLE ROW LEVEL SECURITY;

-- 3. Limpiar políticas anteriores para evitar conflictos
DROP POLICY IF EXISTS "Permitir lectura pública de registros" ON public.registros;
DROP POLICY IF EXISTS "Permitir lectura publica de registros" ON public.registros;
DROP POLICY IF EXISTS "Permitir inserción pública de registros" ON public.registros;
DROP POLICY IF EXISTS "Permitir insercion publica de registros" ON public.registros;

-- 4. Política de Lectura (SELECT) para usuarios anónimos y autenticados
CREATE POLICY "Permitir lectura publica de registros"
ON public.registros
FOR SELECT
TO anon, authenticated
USING (true);

-- 5. Política de Inserción (INSERT) para usuarios anónimos y autenticados
CREATE POLICY "Permitir insercion publica de registros"
ON public.registros
FOR INSERT
TO anon, authenticated
WITH CHECK (true);
